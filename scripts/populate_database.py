def create_database(db_path: str):
    """Create and populate the medical database."""
    
    # Remove existing database if present
    db_file = Path(db_path)
    if db_file.exists():
        db_file.unlink()
    
    # Connect to database
    conn = sqlite3.connect(db_path)
    cursor = conn.cursor()
    
    # Create table
    cursor.execute('''
        CREATE TABLE IF NOT EXISTS medical_chunks (
            id INTEGER PRIMARY KEY AUTOINCREMENT,
            protocol_title TEXT NOT NULL,
            content TEXT NOT NULL,
            embedding BLOB NOT NULL
        )
    ''')
    
    # Insert protocols
    for protocol in MEDICAL_PROTOCOLS:
        # Convert float array to blob
        embedding_blob = struct.pack(f'{len(protocol["embedding"])}f', *protocol["embedding"])
        
        cursor.execute(
            'INSERT INTO medical_chunks (protocol_title, content, embedding) VALUES (?, ?, ?)',
            (protocol["title"], protocol["content"].strip(), embedding_blob)
        )
    
    # Commit and close
    conn.commit()
    conn.close()
    
    print(f"✓ Database created successfully at: {db_path}")
    print(f"✓ Inserted {len(MEDICAL_PROTOCOLS)} medical protocols")
    return len(MEDICAL_PROTOCOLS)


